//! Deterministic checked adapters for explicitly exported handwritten Rust code.
use intersect_model::definitions::{
    rcore_behavior::{ir_v2::TypeNode, types::Scalar},
    semantic_bindings::Contract,
};
pub fn generate(
    contract: &Contract,
    rust_path: &str,
    registration: &str,
    implementation_revision: &str,
) -> Result<String, String> {
    super::identifier(registration)?;
    for segment in rust_path.split("::") {
        if !["crate", "self", "super"].contains(&segment) {
            super::identifier(segment)?;
            if super::KEYWORDS.contains(&segment) {
                return Err("Reserved Rust export path".into());
            }
        }
    }
    if implementation_revision.is_empty() || super::KEYWORDS.contains(&registration) {
        return Err("A valid registration name and implementation revision are required".into());
    }
    let descriptor = contract.descriptor();
    let mut arguments = Vec::new();
    for (index, ty) in descriptor.parameters.iter().enumerate() {
        let node = descriptor
            .types
            .get(ty.0 as usize)
            .ok_or("Unknown argument type")?;
        arguments.push(match node {
            TypeNode::Model(_) => format!("call.model({index})?"),
            other => {
                let native = rust_type(other, &descriptor.types, 0)?;
                format!("call.argument::<{native}>({index}, arguments)?")
            }
        });
    }
    let result_type = rust_type(
        descriptor
            .types
            .get(descriptor.result.0 as usize)
            .ok_or("Unknown result type")?,
        &descriptor.types,
        0,
    )?;
    let args = if arguments.is_empty() {
        String::new()
    } else {
        format!(", {}", arguments.join(", "))
    };
    Ok(format!(
        "// @generated by intersect-codegen semantic-bindings v1. Do not edit.\n\
         pub fn {registration}(registry: &mut intersect_model::semantic_bindings::Registry, contract: &intersect_model::definitions::semantic_bindings::Contract) -> intersect_model::semantic_bindings::Result<()> {{\n\
         use intersect_model::semantic_bindings::{{Error, ErrorKind, NativeProvider}};\n\
         if contract.id() != {id:?} {{ return Err(Error::new(ErrorKind::Contract, \"Generated adapter contract revision mismatch\")); }}\n\
         registry.install(contract, std::rc::Rc::new(NativeProvider::new(contract, {revision:?}, |call: &intersect_model::semantic_bindings::Call<'_>, arguments: &[intersect_model::definitions::rcore_behavior::ir_v2::ValueWire]| {{\n\
         let _ = arguments;\n\
         call.budget.charge(1)?;\n\
         let result: {result_type} = {rust_path}(call{args})?;\n\
         call.result(result)\n\
         }})))\n}}\n",
        id = contract.id(),
        revision = implementation_revision,
    ))
}
fn rust_type(node: &TypeNode, types: &[TypeNode], depth: usize) -> Result<String, String> {
    if depth > 64 {
        return Err("Generated Rust type depth exceeded".into());
    }
    let child = |ty: &intersect_model::definitions::rcore_behavior::ir_v2::TypeId| {
        rust_type(
            types.get(ty.0 as usize).ok_or("Unknown element type")?,
            types,
            depth + 1,
        )
    };
    let native =
        match node {
            TypeNode::Scalar(Scalar::Int8) => "i8",
            TypeNode::Scalar(Scalar::Int16) => "i16",
            TypeNode::Scalar(Scalar::Int32) => "i32",
            TypeNode::Scalar(Scalar::Int64) => "i64",
            TypeNode::Scalar(Scalar::UInt8) => "u8",
            TypeNode::Scalar(Scalar::UInt16) => "u16",
            TypeNode::Scalar(Scalar::UInt32) => "u32",
            TypeNode::Scalar(Scalar::UInt64) => "u64",
            TypeNode::Scalar(Scalar::Bool) => "bool",
            TypeNode::Scalar(Scalar::String) => "String",
            TypeNode::Scalar(Scalar::Unit) => "()",
            TypeNode::Enum(_) | TypeNode::Datatype(_) | TypeNode::AppliedDatatype(_) => {
                "intersect_model::semantic_bindings::NominalValue"
            }
            TypeNode::Option(element) => return Ok(format!("Option<{}>", child(element)?)),
            TypeNode::Collection { kind, element } => {
                use intersect_model::definitions::rcore_behavior::types::CollectionKind;
                let container = match kind {
                    CollectionKind::Sequence => "Vec",
                    CollectionKind::Set => "intersect_model::semantic_bindings::Set",
                    CollectionKind::OrderedSet => "intersect_model::semantic_bindings::OrderedSet",
                    CollectionKind::Bag => "intersect_model::semantic_bindings::Bag",
                };
                return Ok(format!("{container}<{}>", child(element)?));
            }
            _ => return Err(
                "Unsupported generated Rust binding type; no implicit representation conversion"
                    .into(),
            ),
        };
    Ok(native.into())
}

/// An explicit export declaration links checked Rcore authority to handwritten
/// Rust. Code generation does not discover or execute arbitrary Rust symbols.
pub struct Export<'a> {
    pub contract: &'a Contract,
    pub rust_path: &'a str,
    pub registration: &'a str,
    pub implementation_revision: &'a str,
}
/// Generate a package registration that stages all adapters before publication.
pub fn generate_package(exports: &[Export<'_>], registration: &str) -> Result<String, String> {
    super::identifier(registration)?;
    if super::KEYWORDS.contains(&registration) || exports.len() > 64 {
        return Err("Invalid package registration or export count".into());
    }
    let mut names = std::collections::BTreeSet::from([registration]);
    let mut ids = std::collections::BTreeSet::new();
    let mut output = String::new();
    for export in exports {
        if !names.insert(export.registration) || !ids.insert(export.contract.id()) {
            return Err("Duplicate package export or registration".into());
        }
        output.push_str(&generate(
            export.contract,
            export.rust_path,
            export.registration,
            export.implementation_revision,
        )?);
    }
    output.push_str(&format!("pub fn {registration}(registry: &mut intersect_model::semantic_bindings::Registry, contracts: &[intersect_model::definitions::semantic_bindings::Contract]) -> intersect_model::semantic_bindings::Result<()> {{\nif contracts.len() != {} {{ return Err(intersect_model::semantic_bindings::Error::new(intersect_model::semantic_bindings::ErrorKind::Contract, \"Package contract count differs\")); }}\nlet mut staged = intersect_model::semantic_bindings::Registry::default();\n", exports.len()));
    for (i, export) in exports.iter().enumerate() {
        output.push_str(&format!(
            "{}(&mut staged, &contracts[{i}])?;\n",
            export.registration
        ));
    }
    output.push_str("registry.install_package(staged)\n}\n");
    Ok(output)
}
