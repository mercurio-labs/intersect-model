//! Explicit XML export over the native declaration tree. Never used by Rcore compilation.
use super::*;
use crate::definitions::ecore::{Document, Node};
use std::collections::BTreeMap;
type Mapping = (Vec<usize>, SourceSpan, usize, usize);
pub(super) fn xml(document: &Document) -> (String, Vec<Mapping>) {
    let mut text = String::from("<!-- Generated by the native Rcore structural exporter. -->\n");
    let mut mappings = Vec::new();
    let bundle = crate::definitions::bundle::DefinitionBundle {
        version: 1,
        sources: vec![document.source.clone()],
        namespaces: vec![],
    };
    let names = crate::definitions::resources::ResourceSet::new(&bundle)
        .map(|resources| reference_names(document, &resources))
        .unwrap_or_default();
    emit(&document.root, &[], &names, &mut text, &mut mappings);
    (text, mappings)
}
fn emit(
    node: &Node,
    path: &[usize],
    names: &BTreeMap<String, String>,
    text: &mut String,
    mappings: &mut Vec<Mapping>,
) {
    let start = text.len();
    let name = if node.name.namespace.as_deref() == Some(crate::definitions::ecore::XMI) {
        "xmi:XMI"
    } else if node.name.namespace.as_deref() == Some(crate::definitions::ecore::ECORE) {
        "ecore:EPackage"
    } else {
        &node.lexical_name
    };
    text.push('<');
    text.push_str(name);
    if path.is_empty() {
        attr(text, "xmlns:ecore", crate::definitions::ecore::ECORE);
        attr(text, "xmlns:xsi", crate::definitions::ecore::XSI);
        attr(text, "xmlns:xmi", crate::definitions::ecore::XMI);
    }
    for a in &node.attributes {
        if a.name.local == "eType"
            && a.value
                .starts_with(&format!("{}#//", crate::definitions::ecore::ECORE))
        {
            attr(
                text,
                &a.lexical_name,
                &format!("ecore:EDataType {}", a.value),
            );
        } else {
            let value = if is_reference(&a.name.local) {
                a.value
                    .split_whitespace()
                    .map(|word| names.get(word).map_or(word, String::as_str))
                    .collect::<Vec<_>>()
                    .join(" ")
            } else {
                a.value.clone()
            };
            attr(text, &a.lexical_name, &value);
        }
    }
    if node.children.is_empty() {
        text.push_str("/>\n");
    } else {
        text.push_str(">\n");
        for (index, child) in node.children.iter().enumerate() {
            let mut child_path = path.to_vec();
            child_path.push(index);
            emit(child, &child_path, names, text, mappings);
        }
        text.push_str("</");
        text.push_str(name);
        text.push_str(">\n");
    }
    mappings.push((path.to_vec(), node.span.clone(), start, text.len()));
}

fn is_reference(name: &str) -> bool {
    matches!(
        name,
        "eType"
            | "eClassifier"
            | "eTypeParameter"
            | "eOpposite"
            | "eSuperTypes"
            | "eExceptions"
            | "references"
    )
}

// Prefer readable local names only when the shared resolver proves that they
// identify the same declaration. Ambiguous overloads retain positional links.
fn reference_names(
    document: &Document,
    resources: &crate::definitions::resources::ResourceSet,
) -> BTreeMap<String, String> {
    fn visit(
        node: &Node,
        document: &Document,
        resources: &crate::definitions::resources::ResourceSet,
        names: &mut BTreeMap<String, String>,
    ) {
        for attribute in &node.attributes {
            if !is_reference(&attribute.name.local) {
                continue;
            }
            for href in attribute
                .value
                .split_whitespace()
                .filter(|s| s.starts_with("#//"))
            {
                let Ok(id) = resources.resolve(&document.source.id, href) else {
                    continue;
                };
                let mut current = &document.root;
                let mut segments = Vec::new();
                for &index in &id.path {
                    let Some(child) = current.children.get(index) else {
                        break;
                    };
                    let Some(name) = child
                        .attributes
                        .iter()
                        .find(|a| a.name.namespace.is_none() && a.name.local == "name")
                    else {
                        break;
                    };
                    if name.value.is_empty()
                        || !name
                            .value
                            .bytes()
                            .all(|b| b.is_ascii_alphanumeric() || b == b'_')
                    {
                        break;
                    }
                    segments.push(name.value.as_str());
                    current = child;
                }
                if segments.len() != id.path.len() {
                    continue;
                }
                let candidate = format!("#//{}", segments.join("/"));
                if resources
                    .resolve(&document.source.id, &candidate)
                    .is_ok_and(|resolved| resolved == id)
                {
                    names.insert(href.into(), candidate);
                }
            }
        }
        for child in &node.children {
            visit(child, document, resources, names);
        }
    }
    let mut names = BTreeMap::new();
    visit(&document.root, document, resources, &mut names);
    names
}
