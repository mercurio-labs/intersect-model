//! Handwritten, language-neutral Python generation over the canonical schema.
//! Generated wrappers delegate reads to a host; they grant no execution authority.
use crate::definitions::schema::{Feature, Schema};
use serde::Serialize;
use serde_json::{Value, json};
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};

pub const GENERATOR_VERSION: &str = "1";
pub const RUNTIME_API_VERSION: u32 = 1;

#[derive(Debug, Serialize)]
pub struct GeneratedPython {
    pub files: BTreeMap<String, String>,
    pub manifest: Value,
}

fn identifier(name: &str) -> Result<String, String> {
    if name.is_empty()
        || !name
            .bytes()
            .enumerate()
            .all(|(i, c)| c.is_ascii_alphabetic() || c == b'_' || (i > 0 && c.is_ascii_digit()))
        || name.starts_with('_')
    {
        return Err(format!("Unsupported Python identifier {name:?}"));
    }
    let reserved = "False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield match case type";
    Ok(if reserved.split_whitespace().any(|word| word == name) {
        format!("{name}_")
    } else {
        name.to_owned()
    })
}

fn snake(name: &str) -> Result<String, String> {
    let chars: Vec<_> = name.chars().collect();
    let mut result = String::new();
    for (i, c) in chars.iter().copied().enumerate() {
        if c.is_ascii_uppercase()
            && i > 0
            && chars[i - 1] != '_'
            && (chars[i - 1].is_ascii_lowercase()
                || chars[i - 1].is_ascii_digit()
                || chars.get(i + 1).is_some_and(char::is_ascii_lowercase))
        {
            result.push('_');
        }
        result.push(c.to_ascii_lowercase());
    }
    identifier(&result)
}

fn annotation(feature: &Feature, names: &BTreeMap<String, String>) -> (String, Option<String>) {
    let atom = if let Some(name) = names.get(&feature.target) {
        name.clone()
    } else {
        match feature.target.as_str() {
            "EString" | "String" => "str".into(),
            "EBoolean" | "Boolean" => "bool".into(),
            "EInt" | "Integer" => "int".into(),
            _ => {
                return (
                    "object".into(),
                    Some(format!("No Python codec for {}", feature.target)),
                );
            }
        }
    };
    let result = if feature.upper != 1 {
        format!("tuple[{atom}, ...]")
    } else if feature.lower == 0 {
        format!("{atom} | None")
    } else {
        atom
    };
    let unsupported = (feature.derived || feature.volatile)
        .then(|| "Derived/volatile access requires an installed semantic service".into());
    (result, unsupported)
}

/// A deterministic description plus Python source, produced from the same schema
/// used by the engine. No file I/O, Python dependency or language-specific rules.
pub fn generate(schema: &Schema) -> Result<GeneratedPython, String> {
    // Frozen metadata is the read contract, including enums and nominal types;
    // the legacy Schema::validate profile only accepts three builtin scalars.
    crate::core::frozen::Metamodel::freeze(schema).map_err(|e| e.to_string())?;
    let bytes = serde_json::to_vec(schema).map_err(|e| e.to_string())?;
    let fingerprint = format!("sha256:{:x}", Sha256::digest(bytes));
    let mut names = BTreeMap::new();
    let mut used = BTreeSet::from([
        "Enum".to_owned(),
        "cast".to_owned(),
        "REGISTRY".to_owned(),
        "SCHEMA_FINGERPRINT".to_owned(),
    ]);
    for key in schema.classes.keys().chain(schema.enumerations.keys()) {
        let declared = schema
            .declarations
            .get(key)
            .map_or(key.as_str(), |d| d.name.as_str());
        let name = identifier(declared)?;
        if !used.insert(name.clone()) {
            return Err(format!("Python type name collision: {name} ({key})"));
        }
        names.insert(key.clone(), name);
    }
    let header = format!(
        "# GENERATED by Intersect Python generator v{GENERATOR_VERSION}. Do not edit.\n\
         from __future__ import annotations\nfrom enum import Enum\nfrom typing import cast\nfrom ._api import Element as _Element\n\
         SCHEMA_FINGERPRINT = {fingerprint:?}\n\n"
    );
    let mut source = header;
    let mut classes = BTreeMap::new();
    let mut enums = BTreeMap::new();
    for (key, enumeration) in &schema.enumerations {
        let name = &names[key];
        source.push_str(&format!("class {name}(Enum):\n"));
        let mut literal_names = BTreeSet::new();
        let mut literals = Vec::new();
        for literal in enumeration.literals() {
            let python = identifier(&literal.name)?;
            if !literal_names.insert(python.clone()) {
                return Err(format!("Python enum literal collision in {name}: {python}"));
            }
            let wire = json!({"kind":"enum", "enumeration":enumeration.declaration(), "literal":literal.declaration});
            let encoded = serde_json::to_string(&wire).map_err(|e| e.to_string())?;
            source.push_str(&format!("    {python} = {encoded:?}\n"));
            literals.push(json!({"python":python,"wire":wire}));
        }
        if literals.is_empty() {
            source.push_str("    pass\n");
        }
        source.push('\n');
        enums.insert(key.clone(), json!({"python":name,"literals":literals}));
    }
    // Every wrapper has one Python base. Subtyping is checked against the native
    // metamodel, avoiding Python C3 restrictions on valid language inheritance.
    for (key, class) in &schema.classes {
        let name = &names[key];
        source.push_str(&format!(
            "class {name}(_Element):\n    __slots__ = ()\n    _class_key = {key:?}\n"
        ));
        let mut members = BTreeMap::new();
        let reserved_members = [
            "id",
            "metaclass",
            "source_location",
            "stored_properties",
            "container",
            "children",
            "get",
            "is_instance",
        ];
        let mut member_names = BTreeSet::new();
        for effective in schema.effective_features(key)? {
            let field = effective.feature;
            let mut python = snake(&field.name)?;
            if reserved_members.contains(&python.as_str()) {
                python.push('_');
            }
            if !member_names.insert(python.clone()) {
                return Err(format!("Python member name collision in {key}: {python}"));
            }
            let (annotation, unsupported) = annotation(field, &names);
            source.push_str(&format!(
                "\n    @property\n    def {python}(self) -> {annotation}:\n        return cast({annotation}, self.get({:?}))\n", field.name
            ));
            members.insert(
                field.name.clone(),
                json!({
                    "python":python,"annotation":annotation,"identity":effective.identity,
                    "feature":field,"unsupported":unsupported,
                }),
            );
        }
        source.push('\n');
        classes.insert(
            key.clone(),
            json!({"python":name,"declaration":schema.declarations.get(key),
            "parents":class.parents,"abstract":class.abstract_type,"features":members,
            "operations":class.operations,"structured_creation":false}),
        );
    }
    source.push_str("REGISTRY = {\n");
    for (key, name) in &names {
        if schema.classes.contains_key(key) {
            source.push_str(&format!("    {key:?}: {name},\n"));
        }
    }
    source.push_str("}\n");
    Ok(GeneratedPython {
        files: BTreeMap::from([
            ("_generated.py".into(), source),
            ("py.typed".into(), String::new()),
        ]),
        manifest: json!({"format":1,"runtime_api":RUNTIME_API_VERSION,
            "generator":GENERATOR_VERSION,"schema_fingerprint":fingerprint,
            "schema_revision":schema.revision,"schema_namespace":schema.uri,
            "classes":classes,"enums":enums,"datatypes":schema.datatypes,
            "capabilities":{"stored_inspection":true,"structured_creation":false,
                "derived_queries":false,"evaluation":false}}),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    fn schema() -> Schema {
        serde_json::from_value(json!({"revision":"fixture-v1","uri":"urn:python:test","name":"test",
            "classes":{"Node":{"name":"Node","abstract_type":false,"parents":[],"features":{
                "class":{"name":"class","target":"EString","reference":false,"containment":false,
                    "opposite":null,"lower":0,"upper":1,"unique":true,"ordered":true,"derived":false,"default":null},
                "children":{"name":"children","target":"Node","reference":true,"containment":true,
                    "opposite":null,"lower":0,"upper":-1,"unique":true,"ordered":true,"derived":false,"default":[]}
            }}}})).unwrap()
    }
    #[test]
    fn deterministic_names_and_identity() {
        // Host conveniences get a suffix; native names and identities survive.
        let mut schema = schema();
        let escaped = generate(&schema).unwrap();
        assert!(escaped.files["_generated.py"].contains("def children_(self)"));
        let class_field = schema.classes["Node"].features["class"].clone();
        schema.classes.get_mut("Node").unwrap().features.insert(
            "metaclass".into(),
            Feature {
                name: "metaclass".into(),
                ..class_field.clone()
            },
        );
        let escaped = generate(&schema).unwrap();
        assert!(escaped.files["_generated.py"].contains("def metaclass_(self)"));
        assert_eq!(
            escaped.manifest["classes"]["Node"]["features"]["metaclass"]["python"],
            "metaclass_"
        );
        let field = schema
            .classes
            .get_mut("Node")
            .unwrap()
            .features
            .remove("children")
            .unwrap();
        schema.classes.get_mut("Node").unwrap().features.insert(
            "nodes".into(),
            Feature {
                name: "nodes".into(),
                ..field
            },
        );
        let first = generate(&schema).unwrap();
        assert_eq!(first.files, generate(&schema).unwrap().files);
        assert!(first.files["_generated.py"].contains("def class_(self) -> str | None"));
        assert!(first.files["_generated.py"].contains("tuple[Node, ...]"));
        assert_eq!(
            first.manifest["classes"]["Node"]["features"]["nodes"]["feature"]["containment"],
            true
        );
        schema.revision = "fixture-v2".into();
        assert_ne!(
            first.manifest["schema_fingerprint"],
            generate(&schema).unwrap().manifest["schema_fingerprint"]
        );
        schema.classes.get_mut("Node").unwrap().features.insert(
            "class_".into(),
            Feature {
                name: "class_".into(),
                ..class_field
            },
        );
        assert!(generate(&schema).unwrap_err().contains("collision"));
    }
}
