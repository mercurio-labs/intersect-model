//! Handwritten generator for typed views over a frozen model.
use super::{GenerationResult, KEYWORDS, identifier, literal, snake};
use crate::{
    core::frozen::Metamodel,
    definitions::{
        bundle::{DefinitionBundle, DefinitionSource, SourceKind},
        compiler::compile_structure_bundle_with_limits,
        ecore::ParseLimits,
        operations::{TypeTarget, TypedElement},
        rcore::feature_redefinitions,
        schema::{EffectiveFeature, Schema},
    },
};
use std::collections::{BTreeMap, BTreeSet};

/// Compile a canonical, standalone Rcore source with its original logical URI.
pub fn generate_rcore(
    source: DefinitionSource,
    namespace: &str,
    limits: ParseLimits,
) -> GenerationResult<String> {
    if source.kind != SourceKind::Rcore {
        return Err("Frozen Rust bindings require an Rcore source".into());
    }
    let bundle = DefinitionBundle {
        version: 1,
        sources: vec![source.clone()],
        namespaces: vec![],
    };
    let schema = compile_structure_bundle_with_limits(&bundle, &source.id, namespace, limits)
        .map_err(|error| error.to_string())?;
    let redefinitions =
        feature_redefinitions(&source, limits).map_err(|error| error.to_string())?;
    let metamodel = Metamodel::freeze(&schema)
        .and_then(|metamodel| metamodel.with_redefinitions(&redefinitions))
        .map_err(|error| error.to_string())?;
    generate(&metamodel)
}

/// Generate a module for a checked frozen metamodel, including its read layout.
pub fn generate(metamodel: &Metamodel) -> GenerationResult<String> {
    let schema = metamodel.schema();
    if schema
        .generic_signatures
        .as_ref()
        .is_some_and(|inventory| !inventory.parameters.is_empty())
        || !schema.instantiations.is_empty()
    {
        return Err("Frozen Rust bindings do not support generic schemas".into());
    }
    if !schema.datatypes.is_empty() {
        return Err("Frozen Rust bindings do not support declared datatypes".into());
    }
    let digest = metamodel.digest().map_err(|error| error.to_string())?;
    let mut names = BTreeSet::from([
        "ModelView",
        "DerivedValues",
        "Model",
        "Obj",
        "ObjId",
        "FeatureId",
        "ValueRef",
        "Operation",
        "OperationContract",
        "Option",
        "Result",
        "String",
        "Vec",
    ]);
    for name in schema.classes.keys().chain(schema.enumerations.keys()) {
        identifier(name)?;
        if KEYWORDS.contains(&name.as_str()) || !names.insert(name) {
            return Err(format!("Rust type name collision: {name}"));
        }
    }
    let mut output =
        String::from("// GENERATED by intersect-codegen for the frozen model. Do not edit.\n");
    output.push_str(PREAMBLE);
    output += &format!("pub const METAMODEL_DIGEST: [u8; 32] = {digest:?};\n");
    output += &format!(
        "pub const SCHEMA_URI: &str = {};\npub const SCHEMA_REVISION: &str = {};\n",
        literal(&schema.uri),
        literal(&schema.revision)
    );
    for (name, enumeration) in &schema.enumerations {
        emit_enum(&mut output, name, enumeration)?;
    }
    for class in schema.classes.keys() {
        emit_class(&mut output, schema, class)?;
    }
    Ok(output)
}

const PREAMBLE: &str = r#"
use intersect_model::core::frozen::{FeatureId, Model, Obj, ObjId, ValueRef};
use intersect_model::definitions::operations::Operation;

/// An exact operation declaration with its Rust argument tuple and result type.
pub struct OperationContract<'m, Arguments, Output> {
    declaration: &'m Operation,
    signature: std::marker::PhantomData<fn(Arguments) -> Output>,
}

impl<'m, Arguments, Output> OperationContract<'m, Arguments, Output> {
    pub fn declaration(&self) -> &'m Operation {
        self.declaration
    }
}

/// A frozen model checked once against the generated module's metamodel.
#[derive(Clone, Copy)]
pub struct ModelView<'m>(&'m Model);

impl<'m> ModelView<'m> {
    pub fn bind(model: &'m Model) -> Result<Self, String> {
        if model.metamodel().schema().uri != SCHEMA_URI ||
            model.metamodel().digest().map_err(|error| error.to_string())? != METAMODEL_DIGEST {
            return Err("Frozen Rust binding metamodel mismatch".into());
        }
        Ok(Self(model))
    }

    fn accepts(self, object: Obj<'m>, class: &str) -> bool {
        let metamodel = self.0.metamodel();
        metamodel.class(class).is_some_and(|class| metamodel.is_a(object.class(), class))
    }

    #[allow(dead_code)]
    fn feature(self, owner: &str, name: &str) -> Result<FeatureId, String> {
        let metamodel = self.0.metamodel();
        metamodel.class(owner).and_then(|class| {
            metamodel.class_info(class)?.features.iter().copied().find(|feature| {
                metamodel.feature_name(*feature) == name &&
                metamodel.feature_info(*feature).is_some_and(|info| info.owner == class)
            })
        })
            .ok_or_else(|| format!("Missing declaration {owner}.{name}"))
    }

    #[allow(dead_code)]
    fn operation<Arguments, Output>(
        self, owner: &str, name: &str, index: usize,
    ) -> Result<OperationContract<'m, Arguments, Output>, String> {
        let declaration = self.0.metamodel().schema().classes.get(owner)
            .and_then(|class| class.operations.get(index))
            .filter(|operation| operation.name == name)
            .ok_or_else(|| format!("Missing operation declaration {owner}.{name}"))?;
        Ok(OperationContract { declaration, signature: std::marker::PhantomData })
    }
}

// A provider reads an exact feature declaration on the supplied receiver.
pub trait DerivedValues {
    fn read(&self, model: &Model, receiver: ObjId, feature: FeatureId)
        -> Result<serde_json::Value, String>;
}

#[allow(dead_code)]
fn attribute_json(value: ValueRef<'_>) -> Result<serde_json::Value, String> {
    match value {
        ValueRef::Str(value) => Ok(serde_json::Value::from(value)),
        ValueRef::Bool(value) => Ok(serde_json::Value::from(value)),
        ValueRef::Int(value) => Ok(serde_json::Value::from(value)),
        ValueRef::Default(value) | ValueRef::Json(value) => Ok(value.clone()),
        ValueRef::Null => Ok(serde_json::Value::Null),
        _ => Err("Expected an attribute value".into()),
    }
}
"#;

fn emit_enum(
    output: &mut String,
    name: &str,
    enumeration: &crate::definitions::enums::Enumeration,
) -> GenerationResult<()> {
    *output += &format!(
        "#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n#[allow(non_camel_case_types)]\npub enum {name} {{\n"
    );
    let mut names = BTreeMap::new();
    for member in enumeration.literals() {
        identifier(&member.name)?;
        let mut variant = member.name.clone();
        variant[..1].make_ascii_uppercase();
        if KEYWORDS.contains(&variant.as_str())
            || names.insert(variant.clone(), &member.name).is_some()
        {
            return Err(format!("Rust enum variant collision in {name}: {variant}"));
        }
        *output += &format!("    {variant},\n");
    }
    *output += &format!(
        "}}\nimpl {name} {{\n    pub fn from_value(model: ModelView<'_>, value: &serde_json::Value) -> Result<Self, String> {{\n        let value = serde_json::from_value(value.clone()).map_err(|error| error.to_string())?;\n        let enumeration = model.0.metamodel().schema().enumerations.get({}).ok_or(\"Missing enum declaration\")?;\n        match enumeration.validate_value(&value)?.name.as_str() {{\n",
        literal(name)
    );
    for (variant, name) in names {
        *output += &format!("            {} => Ok(Self::{variant}),\n", literal(name));
    }
    *output +=
        "            name => Err(format!(\"Unknown literal {name}\")),\n        }\n    }\n}\n";
    Ok(())
}

fn emit_class(output: &mut String, schema: &Schema, name: &str) -> GenerationResult<()> {
    let class = &schema.classes[name];
    let key = literal(name);
    *output += &format!(
        r#"
#[derive(Clone, Copy)]
pub struct {name}<'m>(ModelView<'m>, Obj<'m>);

impl<'m> {name}<'m> {{
    pub const CLASS: &'static str = {key};

    /// Bind a model-local object ID from the supplied model.
    pub fn bind(model: ModelView<'m>, id: ObjId) -> Option<Self> {{
        let object = model.0.obj(id)?;
        model.accepts(object, Self::CLASS).then_some(Self(model, object))
    }}

    pub fn lookup(model: ModelView<'m>, identity: &str) -> Option<Self> {{
        Self::bind(model, model.0.lookup(identity)?.id())
    }}

    pub fn object(self) -> Obj<'m> {{
        self.1
    }}
"#
    );
    let mut ancestors = BTreeSet::new();
    let mut pending: Vec<_> = class.parents.iter().collect();
    while let Some(parent) = pending.pop() {
        if ancestors.insert(parent) {
            pending.extend(schema.classes[parent].parents.iter());
        }
    }
    let mut names = BTreeSet::from(["bind".to_owned(), "lookup".into(), "object".into()]);
    for parent in ancestors {
        let method = format!("as_{}", snake(parent)?);
        if !names.insert(method.clone()) {
            return Err(format!(
                "Rust ancestor conversion collision in {name}: {method}"
            ));
        }
        *output +=
            &format!("    pub fn {method}(self) -> {parent}<'m> {{ {parent}(self.0, self.1) }}\n");
    }
    let members = schema.effective_features(name)?;
    let mut accessors: BTreeMap<String, Vec<&EffectiveFeature<'_>>> = BTreeMap::new();
    for member in &members {
        accessors
            .entry(snake(&member.feature.name)?)
            .or_default()
            .push(member);
    }
    for (method, members) in accessors {
        let member = match members.as_slice() {
            [member] => Some(*member),
            _ => {
                let mut declared = members
                    .iter()
                    .copied()
                    .filter(|member| member.owner == name);
                let member = declared.next();
                if declared.next().is_some() {
                    return Err(format!("Rust feature collision in {name}: {method}"));
                }
                member
            }
        };
        if let Some(member) = member {
            if !names.insert(method.clone()) {
                return Err(format!("Rust feature collision in {name}: {method}"));
            }
            emit_feature(output, schema, &method, member)?;
        }
    }
    for (index, operation) in class.operations.iter().enumerate() {
        let operation_name = snake(&operation.name)?;
        let method = if class
            .operations
            .iter()
            .filter(|other| other.name == operation.name)
            .count()
            == 1
        {
            format!("operation_{operation_name}")
        } else {
            format!("operation_{operation_name}_{index}")
        };
        if !names.insert(method.clone()) {
            return Err(format!("Rust operation collision in {name}: {method}"));
        }
        let parameters = operation
            .parameters
            .iter()
            .map(|parameter| operation_type(&parameter.value))
            .collect::<GenerationResult<Vec<_>>>()?;
        let arguments = match parameters.as_slice() {
            [parameter] => format!("({parameter},)"),
            _ => format!("({})", parameters.join(", ")),
        };
        let result = operation_type(&operation.result)?;
        // Keep the complete metamodel signature visible at the method.
        *output += &format!(
            "    #[allow(clippy::type_complexity)]\n    pub fn {method}(self) -> Result<OperationContract<'m, {arguments}, {result}>, String> {{\n        self.0.operation(Self::CLASS, {}, {index})\n    }}\n",
            literal(&operation.name)
        );
    }
    *output += "}\n";
    Ok(())
}

fn scalar_type(target: &str) -> GenerationResult<&'static str> {
    match target {
        "EBoolean" => Ok("bool"),
        "EString" => Ok("String"),
        "EInt" => Ok("i32"),
        "EDouble" => Ok("f64"),
        other => Err(format!("Unsupported frozen scalar type {other}")),
    }
}

fn multiplicity_type(rust_type: String, lower: usize, upper: i32) -> String {
    if upper != 1 {
        format!("Vec<{rust_type}>")
    } else if lower == 0 {
        format!("Option<{rust_type}>")
    } else {
        rust_type
    }
}

fn operation_type(element: &TypedElement) -> GenerationResult<String> {
    let rust_type = match &element.target {
        None => return Ok("()".into()),
        Some(TypeTarget::Class(name)) => format!("{name}<'m>"),
        Some(TypeTarget::Enumeration(name)) => name.clone(),
        Some(TypeTarget::Builtin(name)) => scalar_type(name)?.to_owned(),
        Some(other) => return Err(format!("Unsupported frozen operation type {other:?}")),
    };
    Ok(multiplicity_type(rust_type, element.lower, element.upper))
}

fn emit_feature(
    output: &mut String,
    schema: &Schema,
    method: &str,
    member: &EffectiveFeature<'_>,
) -> GenerationResult<()> {
    let feature = member.feature;
    let owner = literal(member.owner);
    let name = literal(&feature.name);
    let target = &feature.target;
    let enumeration = schema.enumerations.contains_key(target);
    let rust_type = if feature.reference {
        format!("{target}<'m>")
    } else if enumeration {
        target.clone()
    } else {
        scalar_type(target)
            .map_err(|error| format!("{error} for {owner}.{name}"))?
            .to_owned()
    };
    let many = feature.upper != 1;
    let optional = feature.lower == 0 && !many;
    let result = multiplicity_type(rust_type, feature.lower, feature.upper);
    let provider = if feature.derived {
        ", provider: &impl DerivedValues"
    } else {
        ""
    };
    *output += &format!(
        "    pub fn {method}(self{provider}) -> Result<{result}, String> {{\n        let feature = self.0.feature({owner}, {name})?;\n"
    );
    let required = ".ok_or(\"Required feature is absent\")";
    if feature.derived {
        *output += "        let feature = self.0.0.metamodel().redefined_by(self.1.class(), feature).unwrap_or(feature);\n        let value = provider.read(self.0.0, self.1.id(), feature)?;\n";
        if feature.reference {
            *output += &format!(
                "        let convert = |id: String| {target}::lookup(self.0, &id).ok_or_else(|| format!(\"Invalid reference {{id}}\"));\n"
            );
            let expression = if many {
                "serde_json::from_value::<Vec<String>>(value).map_err(|e| e.to_string())?.into_iter().map(convert).collect()"
            } else if optional {
                "serde_json::from_value::<Option<String>>(value).map_err(|e| e.to_string())?.map(convert).transpose()"
            } else {
                "convert(serde_json::from_value(value).map_err(|e| e.to_string())?)"
            };
            *output += &format!("        {expression}\n");
        } else if enumeration {
            emit_enum_read(output, target, many, optional, false);
        } else {
            *output += "        serde_json::from_value(value).map_err(|error| error.to_string())\n";
        }
    } else if feature.reference {
        let binding = if many { "let values" } else { "let mut values" };
        *output += &format!(
            "        {binding} = self.1.refs(feature).map(|object| {target}::bind(self.0, object.id()).ok_or_else(|| format!(\"Invalid reference {{}}\", object.identity())));\n"
        );
        let expression = if many {
            "values.collect()".to_owned()
        } else if optional {
            "values.next().transpose()".to_owned()
        } else {
            format!("values.next(){required}?")
        };
        *output += &format!("        {expression}\n");
    } else {
        *output +=
            "        let value = self.1.get(feature).ok_or(\"Feature has no stored value\")?;\n";
        if enumeration {
            emit_enum_read(output, target, many, optional, true);
        } else if many {
            *output += "        let decode = |value| serde_json::from_value(attribute_json(value)?).map_err(|error| error.to_string());\n        match value { ValueRef::Many(items) => items.iter().map(decode).collect(), value => serde_json::from_value(attribute_json(value)?).map_err(|error| error.to_string()) }\n";
        } else {
            *output += "        serde_json::from_value(attribute_json(value)?).map_err(|error| error.to_string())\n";
        }
    }
    *output += "    }\n";
    Ok(())
}

fn emit_enum_read(output: &mut String, target: &str, many: bool, optional: bool, stored: bool) {
    *output += &format!(
        "        let decode = |value: &serde_json::Value| {target}::from_value(self.0, value);\n"
    );
    if stored {
        *output += "        let json = |value: ValueRef<'m>| match value { ValueRef::Json(value) | ValueRef::Default(value) => Ok(value), ValueRef::Null => Ok(&serde_json::Value::Null), _ => Err(\"Expected an enum value\") };\n";
        if many {
            *output += "        if let ValueRef::Many(items) = value { return items.iter().map(|value| decode(json(value)?)).collect(); }\n";
        }
        *output += "        let value = json(value)?;\n";
    } else {
        *output += "        let value = &value;\n";
    }
    *output += if many {
        "        value.as_array().ok_or(\"Expected a collection\")?.iter().map(decode).collect()\n"
    } else if optional {
        "        (!value.is_null()).then(|| decode(value)).transpose()\n"
    } else {
        "        decode(value)\n"
    };
}
