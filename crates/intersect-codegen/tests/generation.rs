fn migrate(text: &str) -> Result<String, String> {
    use intersect_model::definitions::{
        bundle::{DefinitionSource, SourceKind},
        ecore_migration::migrate_ecore,
    };
    let report = migrate_ecore(
        DefinitionSource::new("memory:original.ecore", SourceKind::Ecore, text),
        "memory:model.rcore",
    )
    .map_err(|e| e.to_string())?;
    report
        .converted
        .map(|s| s.text)
        .ok_or_else(|| format!("{:?}", report.issues))
}
fn generate_migrated(text: &str) -> Result<String, String> {
    generate_rcore(&migrate(text)?)
}
