use intersect_model::codegen::{generate, generate_rcore};
use intersect_model::definitions::dynamic::{ScalarType, SchemaBuilder};

const ECORE: &str = include_str!("../../../fixtures/library/library.ecore");

#[test]
fn deterministic_output_and_exact_source_revision() -> Result<(), String> {
    let migrated = migrate(ECORE)?;
    let first = generate_rcore(&migrated)?;
    assert_eq!(first, generate_migrated(ECORE)?);
    let source = intersect_model::definitions::bundle::DefinitionSource::new(
        "memory:model.rcore",
        intersect_model::definitions::bundle::SourceKind::Rcore,
        &migrated,
    );
    let bundle = intersect_model::definitions::bundle::DefinitionBundle {
        version: 1,
        sources: vec![source.clone()],
        namespaces: vec![],
    };
    let schema = intersect_model::definitions::rcore::compile_structure(&bundle, &source.id)
        .map_err(|e| format!("{e:?}"))?
        .schema;
    assert!(first.contains(&format!(
        "pub const SCHEMA_REVISION: &str = {:?};",
        schema.revision
    )));
    assert!(first.contains(&format!("Some({migrated:?})")));
    assert!(first.starts_with("// GENERATED by intersect-codegen."));
    let ir_output = generate(&schema)?;
    assert!(ir_output.contains("pub const RCORE_SOURCE: Option<&str> = None;"));
    assert!(ir_output.contains(&format!(
        "pub const SCHEMA_REVISION: &str = {:?};",
        schema.revision
    )));
    assert_ne!(generate_rcore(&format!("{migrated}\n"))?, first);
    Ok(())
}

#[test]
fn rejects_unsupported_ecore_without_silent_omission() {
    for source in [
        ECORE.replace("ecore:EClass", "ecore:EEnum"),
        ECORE.replace("name=\"Named\"", "name=\"Named\" interface=\"true\""),
        ECORE.replace("#//Named", "elsewhere.ecore#//Named"),
        ECORE.replace("#//EInt", "#//ELong"),
        ECORE.replace("<eClassifiers xsi:type=\"ecore:EClass\" name=\"Member\" eSuperTypes=\"#//Named\"/>",
            "<eClassifiers xsi:type=\"ecore:EClass\" name=\"Member\"><eOperations name=\"run\"/></eClassifiers>"),
    ] {
        assert!(generate_migrated(&source).is_err(), "{source}");
    }
}

#[test]
fn rejects_invalid_and_colliding_rust_names() -> Result<(), String> {
    for class_name in [
        "type",
        "Self",
        "String",
        "i32",
        "SCHEMA_URI",
        "__Hidden",
        "Bad-Name",
        "1Class",
        "λ",
    ] {
        let mut builder = SchemaBuilder::new("names", "urn:test:names");
        builder.class(class_name)?;
        let schema = builder.build()?;
        assert!(generate(schema.as_schema()).is_err(), "{class_name}");
    }
    for feature_names in [
        vec!["id"],
        vec!["queryBinding"],
        vec!["title", "setTitle"],
        vec!["title", "unsetTitle"],
        vec!["title", "isSetTitle"],
        vec!["URLValue", "url_value"],
        vec!["type", "type_"],
        vec!["a.b"],
    ] {
        let mut builder = SchemaBuilder::new("names", "urn:test:names");
        let class = builder.class("Object")?;
        for feature in feature_names {
            class.attribute(feature, ScalarType::String).optional()?;
        }
        assert!(generate(builder.build()?.as_schema()).is_err());
    }
    let mut builder = SchemaBuilder::new("names", "urn:test:names");
    let parent = builder.class("Named")?;
    let child = builder.class("Child")?;
    child.extends(&parent)?;
    child.attribute("asNamed", ScalarType::String).optional()?;
    assert!(generate(builder.build()?.as_schema()).is_err());
    Ok(())
}

#[test]
fn verifies_schema_before_emitting_and_preserves_programmatic_revision() -> Result<(), String> {
    let mut builder = SchemaBuilder::new("test", "urn:test:generated");
    let class = builder.class("Object")?;
    class
        .attribute("text", ScalarType::String)
        .default("quote\"\n\\λ")?;
    let schema = builder.build()?;
    let source = generate(schema.as_schema())?;
    assert!(source.contains(&format!(
        "pub const SCHEMA_REVISION: &str = {:?};",
        schema.as_schema().revision
    )));
    let mut invalid = schema.as_schema().clone();
    invalid.revision = "dynamic-v1:wrong".into();
    assert!(generate(&invalid).is_err());
    invalid.revision.clear();
    assert!(generate(&invalid).is_err());
    Ok(())
}

#[test]
fn imported_richer_declarations_do_not_imply_generated_bindings() -> Result<(), String> {
    for members in [
        r#"<eClassifiers xsi:type="ecore:EClass" name="Interface" interface="true" abstract="true"/>"#,
        r#"<eClassifiers xsi:type="ecore:EClass" name="Operations"><eOperations name="run"/></eClassifiers>"#,
        r##"<eClassifiers xsi:type="ecore:EClass" name="Left"/><eClassifiers xsi:type="ecore:EClass" name="Right"/><eClassifiers xsi:type="ecore:EClass" name="Both" eSuperTypes="#//Left #//Right"/>"##,
    ] {
        let source = format!(
            r#"<ecore:EPackage xmlns:ecore="http://www.eclipse.org/emf/2002/Ecore" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" name="richer" nsURI="urn:richer" nsPrefix="richer">{members}</ecore:EPackage>"#
        );
        use intersect_model::definitions::bundle::{
            DefinitionBundle, DefinitionSource, SourceKind,
        };
        let canonical =
            DefinitionSource::new("memory:model.rcore", SourceKind::Rcore, migrate(&source)?);
        let bundle = DefinitionBundle {
            version: 1,
            sources: vec![canonical.clone()],
            namespaces: vec![],
        };
        let schema = intersect_model::definitions::rcore::compile_structure(&bundle, &canonical.id)
            .map_err(|errors| format!("{errors:?}"))?
            .schema;
        let error = generate(&schema).unwrap_err();
        assert!(
            error.contains("Rust bindings do not yet support"),
            "{error}"
        );
        assert!(generate_migrated(&source).is_err());
    }
    Ok(())
}

#[test]
fn collection_operation_names_are_reserved_only_when_emitted() -> Result<(), String> {
    for name in [
        "removeValues",
        "insertValues",
        "replaceValues",
        "removeAtValues",
        "moveValues",
    ] {
        let mut builder = SchemaBuilder::new("names", "urn:test:names");
        let class = builder.class("Item")?;
        class
            .attribute("values", ScalarType::String)
            .many()
            .build()?;
        class.attribute(name, ScalarType::String).optional()?;
        assert!(
            generate(builder.build()?.as_schema())
                .unwrap_err()
                .contains("method collision")
        );
    }
    let mut builder = SchemaBuilder::new("names", "urn:test:names");
    let class = builder.class("Item")?;
    class
        .attribute("values", ScalarType::String)
        .many()
        .ordered(false)
        .build()?;
    class
        .attribute("insertValues", ScalarType::String)
        .optional()?;
    let output = generate(builder.build()?.as_schema())?;
    assert!(output.contains("pub fn remove_values"));
    assert!(!output.contains("pub fn move_values"));
    Ok(())
}

#[test]
fn computed_setter_names_follow_mutability_and_participate_in_collisions() -> Result<(), String> {
    for changeable in [true, false] {
        for collision in ["setValue", "unsetValue"] {
            let source = format!(
                r#"<ecore:EPackage xmlns:ecore="http://www.eclipse.org/emf/2002/Ecore" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" name="computed" nsURI="urn:computed">
<eClassifiers xsi:type="ecore:EClass" name="Item">
<eStructuralFeatures xsi:type="ecore:EAttribute" name="value" derived="true" changeable="{changeable}" eType="ecore:EDataType http://www.eclipse.org/emf/2002/Ecore#//EString"/>
<eStructuralFeatures xsi:type="ecore:EAttribute" name="{collision}" eType="ecore:EDataType http://www.eclipse.org/emf/2002/Ecore#//EString"/>
</eClassifiers></ecore:EPackage>"#
            );
            let result = generate_migrated(&source);
            if changeable {
                assert!(result.unwrap_err().contains("method collision"));
            } else {
                assert!(result.is_ok());
            }
        }
    }
    Ok(())
}

