"""Generate Ecore type-parameter identifier rules from pinned Unicode 13, offline."""
import hashlib
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "crates/intersect-model/src/definitions/ecore_identifier.rs"


def ranges():
    data = (ROOT / "fixtures/unicode-13/UnicodeData.txt").read_bytes()
    if hashlib.sha256(data).hexdigest() != "bdbffbbfc8ad4d3a6d01b5891510458f3d36f7170422af4ea2bed3211a73e8bb":
        raise ValueError("Unicode 13 source digest mismatch")
    flags = bytearray(0x110000)
    first = None
    for line in data.decode().splitlines():
        row = line.split(';')
        code = int(row[0], 16)
        if row[1].endswith(', First>'):
            first = code
            continue
        start = first if row[1].endswith(', Last>') else code
        first = None
        category = row[2]
        value = 3 if category in {'Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'Nl', 'Sc', 'Pc'} else 2 if category in {'Nd', 'Mc', 'Mn', 'Cf'} else 0
        flags[start:code + 1] = bytes([value]) * (code + 1 - start)
    # Character.isIdentifierIgnorable control ranges; Ecore additionally forbids $.
    for start, end in [(0, 8), (14, 27), (127, 159)]:
        flags[start:end + 1] = bytes([2]) * (end + 1 - start)
    flags[ord('$')] = 0
    result = []
    start = 0
    for code in range(1, len(flags) + 1):
        if code == len(flags) or flags[code] != flags[start]:
            if flags[start]:
                result.append((start, code - 1, flags[start]))
            start = code
    return result


def generate():
    lines = ["// Generated by tools/ecore_identifier.py; do not edit.",
             "// Unicode 13 source and license: fixtures/unicode-13/.",
             "// Flags: start=1, part=2; Ecore forbids dollar signs.",
             "#[rustfmt::skip]", "const RANGES: &[(u32, u32, u8)] = &["]
    lines.extend(f"    (0x{start:x}, 0x{end:x}, {flags})," for start, end, flags in ranges())
    lines.extend(["];", "", "#[rustfmt::skip]", "pub(crate) fn valid(name: &str) -> bool {",
                  "    fn accepts(c: char, flag: u8) -> bool {",
                  "        let code = c as u32;",
                  "        RANGES.binary_search_by(|(start, end, _)| {",
                  "            if code < *start { std::cmp::Ordering::Greater }",
                  "            else if code > *end { std::cmp::Ordering::Less }",
                  "            else { std::cmp::Ordering::Equal }",
                  "        }).is_ok_and(|index| RANGES[index].2 & flag != 0)",
                  "    }",
                  "    let mut chars = name.chars();",
                  "    chars.next().is_some_and(|c| accepts(c, 1)) && chars.all(|c| accepts(c, 2))",
                  "}", ""])
    return '\n'.join(lines)


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != generated:
            raise SystemExit('Ecore identifier table is stale')
    else:
        OUTPUT.write_text(generated, encoding='utf-8', newline='\n')
