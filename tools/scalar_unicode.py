"""Generate the Java 17 scalar subset from pinned Unicode 13 data, offline."""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "crates/intersect-model/src/definitions/scalar_unicode.rs"


def generate():
    data = (ROOT / "fixtures/unicode-13/UnicodeData.txt").read_bytes()
    if hashlib.sha256(data).hexdigest() != "bdbffbbfc8ad4d3a6d01b5891510458f3d36f7170422af4ea2bed3211a73e8bb":
        raise ValueError("Unicode 13 source digest mismatch")
    rows = {int(row[0], 16): row for row in
            (line.split(';') for line in data.decode().splitlines())}
    digits = [code for code, row in rows.items()
              if code <= 0xffff and row[2] == 'Nd' and row[6] == '0']
    equivalents = []
    for code, row in rows.items():
        upper = int(row[12], 16) if row[12] else code
        upper_row = rows.get(upper)
        folded = int(upper_row[13], 16) if upper_row and upper_row[13] else upper
        if code > 127 and folded in map(ord, 'truefals'):
            equivalents.append((code, folded))
    lines = ["// Generated by tools/scalar_unicode.py; do not edit.",
             "// Unicode 13 source and license: fixtures/unicode-13/.",
             "#[rustfmt::skip]",
             "pub(super) const DECIMAL_ZEROES: &[u32] = &["]
    lines.extend(f"    0x{code:04x}," for code in digits)
    lines.extend(["];", "#[rustfmt::skip]", "pub(super) const BOOLEAN_CASE_EQUIVALENTS: &[(char, char)] = &["])
    lines.extend(f"    ('\\u{{{code:04x}}}', '{chr(folded)}')," for code, folded in equivalents)
    lines.extend(["];", ""])
    return '\n'.join(lines)


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit('Scalar Unicode table is stale')
    else:
        OUTPUT.write_text(generated, encoding='utf-8', newline='\n')
